# Compile the looks's look: the kit sheet first (so its class ids stay 0 to 7), then
# src/styles/*.wolcss, with wolkit-stylec. Writes the class ids (src/looks/style/classes.cr, module
# Looks::Styles) and the compiled table (src/looks/style/table.cr, Looks::STYLE_TABLE), both
# committed so a package build needs no style compiler. Usage: styles.sh STYLEC [--check]; with
# --check it compiles into a temporary folder and fails when the committed files differ.
set -eu
stylec=${1:?usage: styles.sh STYLEC [--check]}
mode=${2:-write}
here=$(cd "$(dirname "$0")/.." && pwd)
kit=$here/../../shards/wolkit/styles/kit.wolcss
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
out=$here/src/looks/style
[ "$mode" = --check ] && out=$tmp/out
mkdir -p "$out"
# The compiler reads its sheets in sorted path order, so all of them go into one folder with the kit
# sheet's name sorting first.
mkdir -p "$tmp/sheets"
cp "$kit" "$tmp/sheets/00-kit.wolcss"
for f in "$here"/src/styles/*.wolcss; do cp "$f" "$tmp/sheets/10-$(basename "$f")"; done
"$stylec" --deny-warnings --out "$tmp/looks.wsb" --crystal "$tmp/styles.cr" "$tmp"/sheets/*.wolcss
{
  printf '%s\n' '# SPDX-License-Identifier: GPL-2.0-or-later'
  printf '%s\n' '# The style class ids of the looks, generated from the kit sheet and src/styles/*.wolcss by'
  printf '%s\n' '# wolkit-stylec (tools/styles.sh); do not edit. The kit ids come first, so they match Wolkit::KitClass.'
  sed -e 's/^module Wolkit::Styles$/module Looks::Styles/' -e '/^# SPDX-License-Identifier:/d' -e '/^# Generated by/d' "$tmp/styles.cr"
} > "$out/classes.cr"
{
  printf '%s\n' '# SPDX-License-Identifier: GPL-2.0-or-later'
  printf '%s\n' '# The looks look compiled (WSB1), generated from the kit sheet and src/styles/*.wolcss by'
  printf '%s\n' '# wolkit-stylec (tools/styles.sh); do not edit. The app loads it with Wolkit.use_styles.'
  printf '%s\n' 'module Looks'
  printf '%s\n' '  STYLE_TABLE = Bytes['
  od -An -v -tu1 -w16 "$tmp/looks.wsb" | sed -e 's/^ *//' -e 's/  */, /g' -e 's/$/,/' -e 's/^/    /'
  printf '%s\n' '  ]'
  printf '%s\n' 'end'
} > "$out/table.cr"
crystal tool format "$out/classes.cr" "$out/table.cr" > /dev/null
if [ "$mode" = --check ]; then
  for f in classes.cr table.cr; do
    cmp -s "$out/$f" "$here/src/looks/style/$f" || { echo "src/looks/style/$f is stale: run make styles" >&2; exit 1; }
  done
  echo "ok   the committed look matches src/styles"
fi
