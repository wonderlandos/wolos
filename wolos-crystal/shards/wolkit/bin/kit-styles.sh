# Compile the default look (styles/kit.wolcss) with wolkit-stylec and write the two Crystal files the
# shard loads: src/wolkit/style/kit_classes.cr (the class ids, module Wolkit::KitClass) and
# src/wolkit/style/kit_table.cr (the compiled WSB1 bytes, Wolkit::KIT_TABLE). Usage:
# kit-styles.sh STYLEC [OUTDIR]  (OUTDIR defaults to src/wolkit/style; spec/scripts/kit_styles.sh
# writes to a temporary directory and compares). `make styles` runs it.
set -eu
stylec=${1:?usage: kit-styles.sh STYLEC [OUTDIR]}
here=$(cd "$(dirname "$0")/.." && pwd)
out=${2:-$here/src/wolkit/style}
tmp=$(mktemp -d)
trap 'rm -rf "$tmp"' EXIT
mkdir -p "$out"
"$stylec" --deny-warnings --out "$tmp/kit.wsb" --crystal "$tmp/styles.cr" "$here/styles/kit.wolcss"
{
  printf '%s\n' '# SPDX-License-Identifier: BSD-2-Clause'
  printf '%s\n' '# The class ids of the default look, generated from styles/kit.wolcss by wolkit-stylec (bin/kit-styles.sh); do not edit.'
  printf '%s\n' '# A class id is its first appearance in the sheet, so the DSL (primary: true) can name them as constants.'
  sed -e 's/^module Wolkit::Styles$/module Wolkit::KitClass/' -e '/^# Generated by/d' "$tmp/styles.cr"
} > "$out/kit_classes.cr"
{
  printf '%s\n' '# SPDX-License-Identifier: BSD-2-Clause'
  printf '%s\n' '# The default look compiled (WSB1), generated from styles/kit.wolcss by wolkit-stylec (bin/kit-styles.sh); do not edit.'
  printf '%s\n' '# Every window uses this table until the app gives its own (Wolkit.use_styles).'
  printf '%s\n' 'module Wolkit'
  printf '%s\n' '  KIT_TABLE = Bytes['
  od -An -v -tu1 -w16 "$tmp/kit.wsb" | sed -e 's/^ *//' -e 's/  */, /g' -e 's/$/,/' -e 's/^/    /'
  printf '%s\n' '  ]'
  printf '%s\n' 'end'
} > "$out/kit_table.cr"
crystal tool format "$out/kit_classes.cr" "$out/kit_table.cr" > /dev/null
