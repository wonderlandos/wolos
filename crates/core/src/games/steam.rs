//! `WolOS Proton`: a Steam compatibility tool that hands Windows games to native wine-proton.
//! Steam is a Linux program (linux-steam-utils), so it runs the launcher with Linux `sh`. The
//! launcher puts back the FreeBSD environment linux-steam-utils saved (`LSU_FBSD_*`, same swap
//! as its `lsu-linux-to-freebsd-env`) and execs `wol-run --steam`, a FreeBSD ELF: the kernel
//! picks the ABI from the ELF brand, so wine-proton and the game run natively. The manifest names
//! no `require_tool_appid`, so Steam starts no Steam Linux Runtime (pressure-vessel).
use super::wine::Version;
use std::io;
use std::path::{Path, PathBuf};

/// Directory under `compatibilitytools.d`.
pub const TOOL_DIR: &str = "WolOS-Proton";
/// Key in `compatibilitytool.vdf` (Steam stores it per game in `config.vdf`): never rename.
pub const TOOL_ID: &str = "WolOS_Proton";
pub const DISPLAY_NAME: &str = "WolOS Proton (native wine-proton)";
pub const LAUNCHER: &str = "wolos-proton";
pub const WOL_RUN: &str = "/usr/local/bin/wol-run";
/// Proton verbs the launcher accepts (`wol-run --steam <verb>`).
pub const VERBS: [&str; 6] = [
    "waitforexitandrun",
    "run",
    "runinprefix",
    "getcompatpath",
    "getnativepath",
    "destroyprefix",
];
/// Variables linux-steam-utils swaps between its FreeBSD and Linux sides.
pub const SWAPPED: [&str; 4] = [
    "LD_PRELOAD",
    "LD_LIBRARY_PATH",
    "LIBGL_DRIVERS_PATH",
    "PATH",
];
/// linux-steam-utils (games/linux-steam-utils).
pub const LSU: &str = "/usr/local/steam-utils";

pub fn compatibility_tool_vdf() -> String {
    format!(
        "\"compatibilitytools\"\n{{\n  \"compat_tools\"\n  {{\n    \"{TOOL_ID}\"\n    {{\n      \
         \"install_path\" \".\"\n      \"display_name\" \"{DISPLAY_NAME}\"\n      \
         \"from_oslist\"  \"windows\"\n      \"to_oslist\"    \"linux\"\n    }}\n  }}\n}}\n"
    )
}

pub fn tool_manifest_vdf() -> String {
    format!("\"manifest\"\n{{\n  \"version\" \"2\"\n  \"commandline\" \"/{LAUNCHER} %verb%\"\n}}\n")
}

/// POSIX sh; runs under Linux bash (from Steam) and FreeBSD sh alike.
pub fn launcher_script(wol_run: &str) -> String {
    let swaps: String = SWAPPED.iter().map(|v| format!("swap {v}\n")).collect();
    format!(
        "#!/bin/sh\n\
         # WolOS Proton launcher. Generated by `wol games steam-setup`; changes are overwritten.\n\
         # Steam runs this under the Linux ABI. Put back the FreeBSD environment linux-steam-utils\n\
         # saved, then exec wol-run (FreeBSD ELF): the game runs on native wine-proton.\n\
         swap() {{\n\
         \teval \"_l=\\${{$1-}} _ls=\\${{$1+1}} _f=\\${{LSU_FBSD_$1-}} _fs=\\${{LSU_FBSD_$1+1}}\"\n\
         \tif [ -n \"$_ls\" ]; then eval \"LSU_LINUX_$1=\\$_l\"; export \"LSU_LINUX_$1\"; else unset \"LSU_LINUX_$1\"; fi\n\
         \tif [ -n \"$_fs\" ]; then eval \"$1=\\$_f\"; export \"$1\"; else unset \"$1\"; fi\n\
         }}\n\
         {swaps}\
         exec {wol_run} --steam \"$@\"\n"
    )
}

/// Steam's install root for this user: `~/.steam/root` (symlink Steam maintains), else
/// `~/.steam/steam` (where linux-steam-utils bootstraps it), else `~/.local/share/Steam`.
pub fn steam_root(home: &Path, exists: &dyn Fn(&Path) -> bool) -> PathBuf {
    let c = [".steam/root", ".steam/steam", ".local/share/Steam"].map(|r| home.join(r));
    c.iter().find(|p| exists(p)).unwrap_or(&c[1]).to_path_buf()
}

pub fn tool_dir(steam_root: &Path) -> PathBuf {
    steam_root.join("compatibilitytools.d").join(TOOL_DIR)
}

/// (file name, content, mode) of the tool.
pub fn tool_files(wol_run: &str) -> [(&'static str, String, u32); 3] {
    [
        ("compatibilitytool.vdf", compatibility_tool_vdf(), 0o644),
        ("toolmanifest.vdf", tool_manifest_vdf(), 0o644),
        (LAUNCHER, launcher_script(wol_run), 0o755),
    ]
}

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub enum Installed {
    Created,
    Updated,
    Current,
}

/// Write the tool into `<steam_root>/compatibilitytools.d/WolOS-Proton`, touching only files
/// whose content or mode differ. Idempotent; Steam picks it up at its next start.
pub fn install(steam_root: &Path, wol_run: &str) -> io::Result<Installed> {
    use std::os::unix::fs::PermissionsExt;
    let dir = tool_dir(steam_root);
    let fresh = !dir.exists();
    std::fs::create_dir_all(&dir)?;
    let mut changed = false;
    for (name, text, mode) in tool_files(wol_run) {
        let p = dir.join(name);
        if std::fs::read_to_string(&p).ok().as_deref() != Some(text.as_str()) {
            let tmp = dir.join(format!(".{name}.tmp"));
            std::fs::write(&tmp, &text)?;
            std::fs::set_permissions(&tmp, std::fs::Permissions::from_mode(mode))?;
            std::fs::rename(&tmp, &p)?;
            changed = true;
        } else if std::fs::metadata(&p)?.permissions().mode() & 0o777 != mode {
            std::fs::set_permissions(&p, std::fs::Permissions::from_mode(mode))?;
            changed = true;
        }
    }
    Ok(match (fresh, changed) {
        (true, _) => Installed::Created,
        (false, true) => Installed::Updated,
        (false, false) => Installed::Current,
    })
}

/// Whether every tool file has the expected content (`wol games doctor`).
pub fn is_current(
    read: &dyn Fn(&Path) -> Option<String>,
    steam_root: &Path,
    wol_run: &str,
) -> bool {
    let dir = tool_dir(steam_root);
    tool_files(wol_run)
        .iter()
        .all(|(name, text, _)| read(&dir.join(name)).as_deref() == Some(text.as_str()))
}

/// `"path"` values of `steamapps/libraryfolders.vdf`.
pub fn library_paths(vdf: &str) -> Vec<String> {
    vdf.lines()
        .filter_map(|l| {
            let q: Vec<&str> = l.split('"').collect();
            // "path"<ws>"value" -> ["", path, ws, value, ""]
            (q.len() >= 5 && q[1] == "path").then(|| q[3].replace("\\\\", "\\"))
        })
        .collect()
}

/// Steam library roots (each holds `steamapps/`), the client root first, no duplicates.
pub fn libraries(steam_root: &Path, read: &dyn Fn(&Path) -> Option<String>) -> Vec<PathBuf> {
    let mut out = vec![steam_root.to_path_buf()];
    let vdf = read(&steam_root.join("steamapps/libraryfolders.vdf")).unwrap_or_default();
    for p in library_paths(&vdf).into_iter().map(PathBuf::from) {
        if !out.contains(&p) {
            out.push(p);
        }
    }
    out
}

/// Valve Proton directory names that carry DXVK/vkd3d-proton/dxvk-nvapi for a wine-proton
/// release, best first.
pub fn proton_names(v: Version) -> Vec<String> {
    vec![
        format!("Proton {}.{}", v.major, v.minor),
        format!("Proton {}.{} (Beta)", v.major, v.minor),
        "Proton - Experimental".into(),
    ]
}

/// Steam app id of Valve's Proton for a release (`steam steam://install/<id>`), from
/// linux-steam-utils' table.
pub fn proton_app_id(v: Version) -> Option<u32> {
    match (v.major, v.minor) {
        (8, 0) => Some(2_348_590),
        (9, 0) => Some(2_805_730),
        (10, 0) => Some(3_658_110),
        (11, 0) => Some(4_628_710),
        _ => None,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn vdf_files_are_exact() {
        assert_eq!(
            compatibility_tool_vdf(),
            r#""compatibilitytools"
{
  "compat_tools"
  {
    "WolOS_Proton"
    {
      "install_path" "."
      "display_name" "WolOS Proton (native wine-proton)"
      "from_oslist"  "windows"
      "to_oslist"    "linux"
    }
  }
}
"#
        );
        let m = tool_manifest_vdf();
        assert_eq!(
            m,
            "\"manifest\"\n{\n  \"version\" \"2\"\n  \"commandline\" \"/wolos-proton %verb%\"\n}\n"
        );
        assert!(
            !m.contains("require_tool_appid"),
            "no Steam Linux Runtime / pressure-vessel"
        );
    }

    #[test]
    fn launcher_swaps_back_then_execs_wol_run() {
        let s = launcher_script("/usr/local/bin/wol-run");
        assert!(s.starts_with("#!/bin/sh\n"));
        for v in SWAPPED {
            assert!(s.contains(&format!("\nswap {v}\n")), "{v}");
        }
        assert!(s.ends_with("exec /usr/local/bin/wol-run --steam \"$@\"\n"));
        for gnuism in ["[[", "local ", "function ", "$'", "declare", "${!"] {
            assert!(!s.contains(gnuism), "POSIX sh only: {gnuism}");
        }
    }

    #[test]
    fn steam_root_preference() {
        let home = Path::new("/home/u");
        for (present, want) in [
            (vec![".steam/root", ".steam/steam"], ".steam/root"),
            (vec![".steam/steam", ".local/share/Steam"], ".steam/steam"),
            (vec![".local/share/Steam"], ".local/share/Steam"),
            (vec![], ".steam/steam"),
        ] {
            let exists = |p: &Path| present.iter().any(|r| home.join(r) == p);
            assert_eq!(steam_root(home, &exists), home.join(want), "{present:?}");
        }
        assert_eq!(
            tool_dir(Path::new("/h/.steam/root")),
            Path::new("/h/.steam/root/compatibilitytools.d/WolOS-Proton")
        );
    }

    #[test]
    fn install_is_idempotent_and_repairs() {
        use std::os::unix::fs::PermissionsExt;
        let home = std::env::temp_dir().join(format!("wol-steam-tool-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&home);
        let root = home.join(".steam/steam");
        let dir = tool_dir(&root);
        assert_eq!(install(&root, WOL_RUN).unwrap(), Installed::Created);
        let read = |p: &Path| std::fs::read_to_string(p).ok();
        assert!(is_current(&read, &root, WOL_RUN));
        let mode = |n: &str| std::fs::metadata(dir.join(n)).unwrap().permissions().mode() & 0o777;
        assert_eq!(mode(LAUNCHER), 0o755);
        assert_eq!(mode("toolmanifest.vdf"), 0o644);
        assert_eq!(install(&root, WOL_RUN).unwrap(), Installed::Current);
        std::fs::write(dir.join("toolmanifest.vdf"), "broken").unwrap();
        std::fs::set_permissions(dir.join(LAUNCHER), std::fs::Permissions::from_mode(0o644))
            .unwrap();
        assert!(!is_current(&read, &root, WOL_RUN));
        assert_eq!(install(&root, WOL_RUN).unwrap(), Installed::Updated);
        assert!(is_current(&read, &root, WOL_RUN));
        assert_eq!(mode(LAUNCHER), 0o755);
        assert!(
            !is_current(&read, &root, "/other/wol-run"),
            "launcher names wol-run"
        );
        let left: Vec<_> = std::fs::read_dir(&dir).unwrap().flatten().collect();
        assert_eq!(left.len(), 3, "no temp files left");
        std::fs::remove_dir_all(home).unwrap();
    }

    #[test]
    fn libraries_from_libraryfolders_vdf() {
        let vdf = r#""libraryfolders"
{
	"0"
	{
		"path"		"/home/u/.steam/steam"
		"label"		""
		"apps"
		{
			"228980"		"1021"
		}
	}
	"1"
	{
		"path"		"/mnt/games/SteamLibrary"
	}
}
"#;
        assert_eq!(
            library_paths(vdf),
            ["/home/u/.steam/steam", "/mnt/games/SteamLibrary"]
        );
        let root = Path::new("/home/u/.steam/steam");
        let read = |p: &Path| (p == root.join("steamapps/libraryfolders.vdf")).then(|| vdf.into());
        assert_eq!(
            libraries(root, &read),
            [root, Path::new("/mnt/games/SteamLibrary")]
        );
        assert_eq!(libraries(root, &|_| None), [root]);
    }

    #[test]
    fn proton_for_release() {
        let v = Version {
            major: 10,
            minor: 0,
        };
        assert_eq!(
            proton_names(v),
            ["Proton 10.0", "Proton 10.0 (Beta)", "Proton - Experimental"]
        );
        assert_eq!(proton_app_id(v), Some(3_658_110));
        assert_eq!(proton_app_id(Version { major: 7, minor: 0 }), None);
    }
}
