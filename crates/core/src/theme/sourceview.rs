//! GtkSourceView 5 style schemes (gnome-text-editor and every GtkSourceView app) from the theme.
//! A light/dark pair linked by metadata, so the editor follows the system appearance live: the
//! active theme fills its own variant, the WolOS base theme the other. Every syntax colour reads
//! at >= 4.5:1 on the editor background (the theme's card). The `*_color` metadata recolours
//! gnome-text-editor's window chrome with the same libadwaita colours as gtk.css.

use super::apps::{adw_pairs, readable, token_color};
use super::{ResolvedTheme, ThemeCatalog};
use shared::theme::Variant;

pub const LIGHT: &str = "wolos-light";
pub const DARK: &str = "wolos-dark";
/// Relative to the toolkit dir and to `$XDG_DATA_HOME`.
pub const FILES: [&str; 2] = [
    "gtksourceview-5/styles/wolos-light.xml",
    "gtksourceview-5/styles/wolos-dark.xml",
];
pub const SYNTAX_CONTRAST: f64 = 4.5;

pub fn scheme_id(v: Variant) -> &'static str {
    match v {
        Variant::Light => LIGHT,
        Variant::Dark => DARK,
    }
}

/// (light scheme, dark scheme): the active theme in its variant, the base theme in the other.
pub fn render(t: &ResolvedTheme) -> [String; 2] {
    let other = match t.variant {
        Variant::Light => Variant::Dark,
        Variant::Dark => Variant::Light,
    };
    let base = ThemeCatalog::builtin()
        .resolve(other.default_theme())
        .expect("built-in base theme");
    let (light, dark) = match t.variant {
        Variant::Light => (t, &base),
        Variant::Dark => (&base, t),
    };
    [scheme(light, LIGHT), scheme(dark, DARK)]
}

/// Syntax roles -> (token, bold, italic). Colours are made readable on the background.
const ROLES: [(&str, &str, bool, bool); 22] = [
    ("def:comment", "dim", false, true),
    ("def:doc-comment-element", "dim", true, true),
    ("def:keyword", "accent", true, false),
    ("def:statement", "accent", true, false),
    ("def:type", "accent", false, false),
    ("def:builtin", "accent", false, false),
    ("def:preprocessor", "warning", false, false),
    ("def:string", "success", false, false),
    ("def:special-char", "warning", false, false),
    ("def:character", "success", false, false),
    ("def:number", "warning", false, false),
    ("def:decimal", "warning", false, false),
    ("def:floating-point", "warning", false, false),
    ("def:base-n-integer", "warning", false, false),
    ("def:boolean", "danger", false, false),
    ("def:special-constant", "danger", false, false),
    ("def:constant", "warning", false, false),
    ("def:identifier", "text", false, false),
    ("def:function", "accent", false, false),
    ("def:heading", "accent", true, false),
    ("def:link-destination", "accent", false, false),
    ("def:net-address", "accent", false, false),
];

pub fn scheme(t: &ResolvedTheme, id: &str) -> String {
    let c = |k: &str| token_color(t, k);
    let bg = c("card");
    let fg = |k: &str| readable(c(k), bg, SYNTAX_CONTRAST).to_hex();
    let kind = if id == DARK { "dark" } else { "light" };
    let mut s = format!(
        "<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n<!-- WolOS {} — generated by `wol theme`; edits are overwritten. -->\n\
         <style-scheme id=\"{id}\" name=\"WolOS {}\" version=\"1.0\">\n  <author>WolOS</author>\n  <description>{}</description>\n  <metadata>\n\
         \x20   <property name=\"variant\">{kind}</property>\n    <property name=\"light-variant\">{LIGHT}</property>\n    <property name=\"dark-variant\">{DARK}</property>\n",
        t.id,
        if id == DARK { "Dark" } else { "Light" },
        xml(&t.name),
    );
    for (k, v) in adw_pairs(t) {
        s += &format!("    <property name=\"{k}\">{v}</property>\n");
    }
    s += "  </metadata>\n";
    let style = |name: &str, attrs: String| format!("  <style name=\"{name}\" {attrs}/>\n");
    let card = bg.to_hex();
    let line = |a: f64| super::apps::mix(bg, c("text"), a).to_hex();
    s += &style(
        "text",
        format!(
            "foreground=\"{}\" background=\"{card}\"",
            c("text").to_hex()
        ),
    );
    s += &style(
        "selection",
        format!(
            "foreground=\"{}\" background=\"{}\"",
            c("accentText").to_hex(),
            c("accent").to_hex()
        ),
    );
    s += &style("cursor", format!("foreground=\"{}\"", c("accent").to_hex()));
    s += &style("current-line", format!("background=\"{}\"", line(0.05)));
    s += &style(
        "line-numbers",
        format!("foreground=\"{}\" background=\"{card}\"", fg("dim")),
    );
    s += &style(
        "current-line-number",
        format!(
            "foreground=\"{}\" background=\"{}\"",
            c("text").to_hex(),
            line(0.05)
        ),
    );
    s += &style(
        "right-margin",
        format!(
            "foreground=\"{}\" background=\"{}\"",
            line(0.12),
            line(0.12)
        ),
    );
    s += &style("draw-spaces", format!("foreground=\"{}\"", line(0.25)));
    s += &style(
        "background-pattern",
        format!("foreground=\"{}\"", line(0.06)),
    );
    s += &style(
        "bracket-match",
        format!("background=\"{}\" bold=\"true\"", line(0.12)),
    );
    s += &style(
        "bracket-mismatch",
        format!("foreground=\"{}\" underline=\"error\"", fg("danger")),
    );
    s += &style(
        "search-match",
        format!(
            "foreground=\"{}\" background=\"{}\"",
            c("accentText").to_hex(),
            c("accent").to_hex()
        ),
    );
    s += &style("map-overlay", format!("background=\"{}\"", line(0.10)));
    for (name, tok, bold, italic) in ROLES {
        let mut a = format!("foreground=\"{}\"", fg(tok));
        if bold {
            a += " bold=\"true\"";
        }
        if italic {
            a += " italic=\"true\"";
        }
        s += &style(name, a);
    }
    s += &style(
        "def:error",
        format!("foreground=\"{}\" underline=\"error\"", fg("danger")),
    );
    s += &style("def:warning", format!("foreground=\"{}\"", fg("warning")));
    s += &style(
        "def:note",
        format!("foreground=\"{}\" bold=\"true\"", fg("accent")),
    );
    s += &style("def:emphasis", "italic=\"true\"".into());
    s += &style("def:strong-emphasis", "bold=\"true\"".into());
    s += &style(
        "def:inline-code",
        format!("foreground=\"{}\"", fg("success")),
    );
    s += &style("def:insertion", format!("foreground=\"{}\"", fg("success")));
    s += &style("def:deletion", format!("foreground=\"{}\"", fg("danger")));
    s += &style("def:underlined", "underline=\"single\"".into());
    s += "</style-scheme>\n";
    s
}

fn xml(s: &str) -> String {
    s.replace('&', "&amp;")
        .replace('<', "&lt;")
        .replace('>', "&gt;")
}

#[cfg(test)]
mod tests {
    use super::*;
    use shared::theme::Color;

    fn attr<'a>(line: &'a str, name: &str) -> Option<&'a str> {
        let k = format!("{name}=\"");
        let i = line.find(&k)? + k.len();
        line[i..].split('"').next()
    }

    #[test]
    fn pair_follows_the_appearance() {
        let cat = ThemeCatalog::builtin();
        let [light, dark] = render(&cat.resolve("ristretto").unwrap());
        assert!(dark.contains("<style-scheme id=\"wolos-dark\""));
        assert!(dark.contains("<property name=\"variant\">dark</property>"));
        assert!(light.contains("<property name=\"dark-variant\">wolos-dark</property>"));
        assert!(dark.contains(&format!(
            "<style name=\"text\" foreground=\"{}\" background=\"#3d2f2a\"/>",
            "#e6d9db"
        )));
        assert!(
            light.contains("<!-- WolOS wol-light"),
            "other variant = base theme"
        );
        assert!(dark.contains("<property name=\"window_bg_color\">#2c2525</property>"));
    }

    /// Markdown headings (`def:heading`) are the theme's accent, made readable on the editor
    /// background: Ristretto's coral, not a stock purple.
    #[test]
    fn headings_are_the_theme_accent() {
        let cat = ThemeCatalog::builtin();
        for s in cat.list() {
            let t = cat.resolve(&s.id).unwrap();
            let x = scheme(&t, scheme_id(t.variant));
            let want = readable(
                token_color(&t, "accent"),
                token_color(&t, "card"),
                SYNTAX_CONTRAST,
            )
            .to_hex();
            let line = x
                .lines()
                .find(|l| l.contains("name=\"def:heading\""))
                .unwrap();
            assert_eq!(attr(line, "foreground"), Some(want.as_str()), "{}", s.id);
            assert_eq!(attr(line, "bold"), Some("true"), "{}", s.id);
        }
        let t = cat.resolve("ristretto").unwrap();
        assert!(scheme(&t, DARK).contains("<style name=\"def:heading\" foreground=\"#f38d70\""));
    }

    #[test]
    fn every_syntax_colour_reads_on_the_editor_background() {
        let cat = ThemeCatalog::builtin();
        for s in cat.list() {
            let t = cat.resolve(&s.id).unwrap();
            let x = scheme(&t, scheme_id(t.variant));
            let bg = token_color(&t, "card");
            for l in x.lines().filter(|l| l.contains("name=\"def:")) {
                let fg = attr(l, "foreground").and_then(Color::parse);
                if let Some(fg) = fg {
                    let r = Color::contrast(fg, bg);
                    assert!(r >= SYNTAX_CONTRAST, "{}: {l} ({r:.2})", s.id);
                }
            }
            assert_eq!(x.matches("<style ").count(), 13 + ROLES.len() + 9);
        }
    }
}
