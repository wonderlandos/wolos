use super::terminal::{self, bare};
use shared::theme::{ANSI_NAMES, Color, Variant};

/// The default theme's render, shipped by the image (`WOL_REGEN=1 cargo test -p core`).
pub const SYSTEM_DIR: &str = "/usr/share/wolos/toolkits";
/// The whole starship config (`STARSHIP_CONFIG`): [`STARSHIP_BASE`] with the theme's palette.
pub const STARSHIP: &str = "starship/palette.toml";
pub const FISH: &str = "fish/colors.fish";
pub const NU: &str = "nu/colors.nu";
pub const BASH: &str = "bash/colors.sh";
pub const PWSH: &str = "pwsh/colors.ps1";
/// A ghostty theme file (`theme = /path/to/it`).
pub const GHOSTTY: &str = "ghostty/theme";
/// A kitty theme (`include`d by the kitty.conf the image ships and wol-session links).
pub const KITTY: &str = "kitty/theme.conf";
/// A zellij theme named [`ZELLIJ_THEME`] (`themes { wolos { ... } }`).
pub const ZELLIJ: &str = "zellij/theme.kdl";
pub const ZELLIJ_THEME: &str = "wolos";
/// A VS Code / Code-OSS colour theme (`contributes.themes[].path` of a theme extension).
pub const VSCODE: &str = "vscode/wolos.json";
pub const FILES: [&str; 9] = [
    STARSHIP, FISH, NU, BASH, PWSH, GHOSTTY, KITTY, ZELLIJ, VSCODE,
];
/// Shipped under [`SYSTEM_DIR`] (the default theme's render). Not starship: its default is the
/// shipped starship.toml itself (`STARSHIP_BASE`), which the shells fall back to.
pub const SHIPPED: [&str; 8] = [FISH, NU, BASH, PWSH, GHOSTTY, KITTY, ZELLIJ, VSCODE];

/// Prompt roles every shell gets, readable on the terminal background (the surface): text roles
/// >= 4.5:1, the autosuggestion dimmer but >= 3:1. Same values as zsh's `WOLOS_PROMPT_*`.
pub fn roles(t: &ResolvedTheme) -> [(&'static str, Color); 6] {
    let bg = token_color(t, "surface");
    let r = |tok: &str| readable(token_color(t, tok), bg, 4.5);
    [
        ("accent", r("accent")),
        ("muted", r("dim")),
        ("ok", r("success")),
        ("error", r("danger")),
        (
            "suggest",
            readable(mix(token_color(t, "dim"), bg, 0.35), bg, 3.0),
        ),
        ("warn", r("warning")),
    ]
}

fn role(t: &ResolvedTheme, name: &str) -> Color {
    roles(t)
        .into_iter()
        .find(|r| r.0 == name)
        .map_or(Color::WHITE, |r| r.1)
}

fn note(t: &ResolvedTheme, comment: &str) -> String {
    format!(
        "{comment} WolOS {} — generated by `wol theme`; edits are overwritten.\n",
        t.id
    )
}

pub fn render(t: &ResolvedTheme) -> Vec<File> {
    [
        (STARSHIP, starship(t)),
        (FISH, fish(t)),
        (NU, nu(t)),
        (BASH, bash(t)),
        (PWSH, pwsh(t)),
        (GHOSTTY, ghostty(t)),
        (KITTY, kitty(t)),
        (ZELLIJ, zellij(t)),
        (VSCODE, vscode(t)),
    ]
    .into_iter()
    .map(|(rel, text)| File { rel, text })
    .collect()
}

/// The shipped starship.toml (`palette = "wolos"`, terminal-colour defaults); the theme's copy is
/// the same file with the `[palettes.wolos]` table set from the theme.
pub const STARSHIP_BASE: &str =
    include_str!("../../../../desktop/overlay/usr/share/wolos/starship/starship.toml");

fn starship(t: &ResolvedTheme) -> String {
    let p = terminal::palette(t);
    let mut table = String::from("[palettes.wolos]\n");
    for (k, c) in roles(t) {
        table += &format!("{k} = \"{}\"\n", c.to_hex());
    }
    table += &format!("text = \"{}\"\n", p.foreground.to_hex());
    table += &format!("surface = \"{}\"\n", p.background.to_hex());
    for (k, c) in ANSI_NAMES.iter().zip(p.ansi) {
        table += &format!("{k} = \"{}\"\n", c.to_hex());
    }
    let mut out = note(t, "#");
    let mut skipping = false;
    let mut placed = false;
    for l in STARSHIP_BASE.lines() {
        let header = l.trim_start().starts_with('[');
        if header && l.trim() == "[palettes.wolos]" {
            out += &table;
            (skipping, placed) = (true, true);
            continue;
        }
        if skipping && !header {
            continue;
        }
        if skipping {
            out.push('\n');
        }
        skipping = false;
        out += l;
        out.push('\n');
    }
    if !placed {
        out += "\n";
        out += &table;
    }
    out
}

fn fish(t: &ResolvedTheme) -> String {
    let h = |n| bare(role(t, n));
    let text = bare(token_color(t, "text"));
    let sel = bare(token_color(t, "accent"));
    let sel_fg = bare(token_color(t, "accentText"));
    let mut s = note(t, "#") + &format!("set -gx WOLOS_THEME {}\n", t.id);
    for (var, v) in [
        ("fish_color_normal", text.clone()),
        ("fish_color_command", h("accent")),
        ("fish_color_keyword", h("accent")),
        ("fish_color_param", text),
        ("fish_color_quote", h("ok")),
        ("fish_color_redirection", h("muted")),
        ("fish_color_end", h("muted")),
        ("fish_color_comment", h("muted")),
        ("fish_color_error", h("error")),
        ("fish_color_operator", h("warn")),
        ("fish_color_escape", h("warn")),
        ("fish_color_autosuggestion", h("suggest")),
        ("fish_color_cancel", h("error")),
        (
            "fish_color_selection",
            format!("{sel_fg} --background={sel}"),
        ),
        ("fish_color_search_match", format!("--background={sel}")),
        ("fish_pager_color_prefix", h("accent")),
        ("fish_pager_color_completion", bare(token_color(t, "text"))),
        ("fish_pager_color_description", h("muted")),
        ("fish_pager_color_progress", h("muted")),
    ] {
        s += &format!("set -g {var} {v}\n");
    }
    for (k, c) in roles(t) {
        s += &format!(
            "set -gx WOLOS_PROMPT_{} '{}'\n",
            k.to_uppercase(),
            c.to_hex()
        );
    }
    s
}

fn nu(t: &ResolvedTheme) -> String {
    let h = |n| role(t, n).to_hex();
    let text = token_color(t, "text").to_hex();
    let mut s = note(t, "#") + &format!("$env.WOLOS_THEME = \"{}\"\n", t.id);
    for (k, c) in roles(t) {
        s += &format!(
            "$env.WOLOS_PROMPT_{} = \"{}\"\n",
            k.to_uppercase(),
            c.to_hex()
        );
    }
    // Merged, so a person's own color_config keys stay.
    s += "$env.config.color_config = ($env.config.color_config? | default {} | merge {\n";
    for (k, v) in [
        ("separator", h("muted")),
        ("header", h("accent")),
        ("row_index", h("muted")),
        ("hints", h("suggest")),
        ("bool", h("warn")),
        ("int", h("warn")),
        ("float", h("warn")),
        ("string", text.clone()),
        ("date", h("ok")),
        ("filesize", h("ok")),
        ("shape_string", h("ok")),
        ("shape_external", h("accent")),
        ("shape_internalcall", h("accent")),
        ("shape_keyword", h("accent")),
        ("shape_flag", h("muted")),
        ("shape_filepath", text.clone()),
        ("shape_bool", h("warn")),
        ("shape_int", h("warn")),
        ("shape_float", h("warn")),
        ("shape_garbage", h("error")),
    ] {
        s += &format!("    {k}: \"{v}\"\n");
    }
    s += "})\n";
    s
}

fn sgr(c: Color) -> String {
    format!("38;2;{};{};{}", c.r, c.g, c.b)
}

const SHELLCHECK_BASH: &str = "# shellcheck shell=bash disable=SC2034\n";

fn bash(t: &ResolvedTheme) -> String {
    // Sourced (no shebang, not executable): the directive names the dialect for shellcheck (and
    // that bashrc reads these names, SC2034), so the CI gate over every `*.sh` checks the shipped
    // copy instead of failing on SC2148.
    let mut s = note(t, "#") + SHELLCHECK_BASH + &format!("WOLOS_THEME={}\n", t.id);
    for (k, c) in roles(t) {
        let k = k.to_uppercase();
        // `#rrggbb`, and the SGR parameters a bash prompt puts between `\e[` and `m`.
        s += &format!(
            "WOLOS_PROMPT_{k}='{}'\nWOLOS_ANSI_{k}='{}'\n",
            c.to_hex(),
            sgr(c)
        );
    }
    s
}

fn pwsh(t: &ResolvedTheme) -> String {
    let esc = |c: Color| format!("\"`e[{}m\"", sgr(c));
    let mut s = note(t, "#") + &format!("$env:WOLOS_THEME = '{}'\n", t.id);
    for (k, c) in roles(t) {
        s += &format!(
            "$env:WOLOS_PROMPT_{} = '{}'\n",
            k.to_uppercase(),
            c.to_hex()
        );
    }
    s += "if (Get-Command Set-PSReadLineOption -ErrorAction SilentlyContinue) {\n    Set-PSReadLineOption -Colors @{\n";
    let text = token_color(t, "text");
    for (k, c) in [
        ("Default", text),
        ("Command", role(t, "accent")),
        ("Keyword", role(t, "accent")),
        ("Parameter", role(t, "muted")),
        ("String", role(t, "ok")),
        ("Comment", role(t, "muted")),
        ("Operator", role(t, "warn")),
        ("Number", role(t, "warn")),
        ("Variable", text),
        ("Type", role(t, "accent")),
        ("Error", role(t, "error")),
        ("InlinePrediction", role(t, "suggest")),
    ] {
        s += &format!("        {k} = {}\n", esc(c));
    }
    s += "    }\n}\n";
    s
}

fn ghostty(t: &ResolvedTheme) -> String {
    let p = terminal::palette(t);
    let mut s = note(t, "#");
    for (i, c) in p.ansi.iter().enumerate() {
        s += &format!("palette = {i}={}\n", c.to_hex());
    }
    for (k, c) in [
        ("background", p.background),
        ("foreground", p.foreground),
        ("cursor-color", p.cursor),
        ("selection-background", p.selection_bg),
        ("selection-foreground", p.selection_fg),
    ] {
        s += &format!("{k} = {}\n", c.to_hex());
    }
    s
}

/// kitty: `key value` lines, the same palette as foot and ghostty, plus the tab bar and window
/// borders from the tokens.
fn kitty(t: &ResolvedTheme) -> String {
    let p = terminal::palette(t);
    let mut s = note(t, "#");
    for (k, c) in [
        ("foreground", p.foreground),
        ("background", p.background),
        ("cursor", p.cursor),
        ("cursor_text_color", p.background),
        ("selection_foreground", p.selection_fg),
        ("selection_background", p.selection_bg),
        ("url_color", token_color(t, "accent")),
        ("active_border_color", token_color(t, "accent")),
        ("inactive_border_color", token_color(t, "line")),
        ("tab_bar_background", token_color(t, "sidebar")),
        ("active_tab_foreground", token_color(t, "accentText")),
        ("active_tab_background", token_color(t, "accent")),
        ("inactive_tab_foreground", role(t, "muted")),
        ("inactive_tab_background", token_color(t, "sidebar")),
    ] {
        s += &format!("{k} {}\n", c.to_hex());
    }
    for (i, c) in p.ansi.iter().enumerate() {
        s += &format!("color{i} {}\n", c.to_hex());
    }
    s
}

fn zellij(t: &ResolvedTheme) -> String {
    let p = terminal::palette(t);
    let a = p.ansi;
    let mut s = note(t, "//") + &format!("themes {{\n    {ZELLIJ_THEME} {{\n");
    for (k, c) in [
        ("fg", p.foreground),
        ("bg", mix(p.background, p.foreground, 0.12)),
        ("black", p.background),
        ("red", a[1]),
        ("green", a[2]),
        ("yellow", a[3]),
        ("blue", a[4]),
        ("magenta", a[5]),
        ("cyan", a[6]),
        ("white", a[7]),
        ("orange", token_color(t, "accent")),
    ] {
        s += &format!("        {k} \"{}\"\n", c.to_hex());
    }
    s += "    }\n}\n";
    s
}

