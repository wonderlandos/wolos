//! Compositor colours from the theme (ADR 0031 themes v2): the title strip (hyprbars bar, title,
//! inactive look) and window shadows. The shipped hyprland.conf holds no colour of its own: it
//! sources [`SYSTEM_HYPR_THEME`] (this render of the default theme) and the window-button file
//! [`LIGHTS`]; `wol theme set` writes the user copy at [`HYPR_THEME_FILE`] (picked up by the user
//! conf's `hypr/wolos/*.conf` glob, after the system one) and sets the same keys live.
use super::ResolvedTheme;
use super::apps::{mix, token_color};
use shared::theme::Color;
pub use shared::theme::{HYPR_THEME_FILE, SYSTEM_HYPR_THEME};

/// WolOS window buttons (one fixed neutral and ink glyphs, not a theme value), sourced once by hyprland.conf:
/// each `hyprbars-button` line adds a button, so they must not sit in a file sourced twice.
pub const LIGHTS: &str = "/usr/share/wolos/hypr/wolos/lights.conf";

/// Compositor `rgba(rrggbbaa)`.
pub fn rgba(c: Color, alpha: u8) -> String {
    format!("rgba({}{alpha:02x})", &c.to_hex()[1..])
}

/// (`hyprctl keyword` name, value), in file order.
pub fn keywords(t: &ResolvedTheme) -> Vec<(&'static str, String)> {
    let (bar, text) = (token_color(t, "surface"), token_color(t, "text"));
    let black = Color::rgb(0, 0, 0);
    vec![
        ("plugin:hyprbars:bar_color", rgba(bar, 0xe6)),
        ("plugin:hyprbars:col.text", rgba(text, 0xff)),
        // Inactive windows look inactive: dimmed buttons, a flatter bar, a dimmer title
        // (bar_color_inactive / col.text_inactive: desktop/hyprland/hyprbars patch).
        (
            "plugin:hyprbars:inactive_button_color",
            rgba(mix(bar, text, 0.22), 0xff),
        ),
        ("plugin:hyprbars:bar_color_inactive", rgba(bar, 0xcc)),
        ("plugin:hyprbars:col.text_inactive", rgba(text, 0x8c)),
        ("decoration:shadow:color", rgba(black, 0x59)),
        ("decoration:shadow:color_inactive", rgba(black, 0x33)),
    ]
}

/// `hypr/wolos/theme.conf`: one `category:key = value` line per keyword.
pub fn conf(t: &ResolvedTheme) -> String {
    let mut s = format!(
        "# WolOS {} — generated by `wol theme`; edits are overwritten.\n",
        t.id
    );
    for (k, v) in keywords(t) {
        s += &format!("{k} = {v}\n");
    }
    s
}

/// Live switch: `hyprctl keyword` per line of [`conf`].
pub fn argv(t: &ResolvedTheme) -> Vec<Vec<String>> {
    keywords(t)
        .into_iter()
        .map(|(k, v)| ["hyprctl", "keyword", k, &v].map(String::from).to_vec())
        .collect()
}

/// A compositor colour literal (`rgb(`, `rgba(`, `0x` + 6 or more hex digits) in the code part of
/// `line` (comments do not count).
pub fn has_colour(line: &str) -> bool {
    let code = line.split('#').next().unwrap_or("");
    code.contains("rgb(")
        || code.contains("rgba(")
        || code.match_indices("0x").any(|(i, _)| {
            code[i + 2..]
                .chars()
                .take_while(char::is_ascii_hexdigit)
                .count()
                >= 6
        })
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::theme::ThemeCatalog;
    use std::path::{Path, PathBuf};

    const SHARE: &str = "desktop/overlay/usr/share/wolos/";

    fn path(rel: &str) -> PathBuf {
        Path::new(env!("CARGO_MANIFEST_DIR"))
            .join("../..")
            .join(rel)
    }

    fn repo(rel: &str) -> String {
        std::fs::read_to_string(path(rel)).unwrap_or_else(|e| panic!("{rel}: {e}"))
    }

    /// Themes own every colour: the shipped hyprland.conf has none left but the black every
    /// compositor starts on (ADR 0012: the loader splash, the greeter and the desktop are one
    /// black picture; `crates/controller/tests/image_seamless.rs`).
    #[test]
    fn hyprland_conf_has_no_colour_literals() {
        let conf = repo(&format!("{SHARE}hypr/hyprland.conf"));
        let left: Vec<&str> = conf
            .lines()
            .filter(|l| has_colour(l))
            .filter(|l| l.trim() != "background_color = rgb(000000)")
            .collect();
        assert!(
            left.is_empty(),
            "colour literals in hyprland.conf: {left:?}"
        );
        let sources: Vec<&str> = conf
            .lines()
            .filter_map(|l| l.trim().strip_prefix("source = "))
            .collect();
        for want in [SYSTEM_HYPR_THEME, LIGHTS] {
            assert_eq!(
                sources.iter().filter(|s| **s == want).count(),
                1,
                "hyprland.conf sources {want} once"
            );
            let rel = want.strip_prefix("/usr/share/wolos/").unwrap();
            assert!(path(&format!("{SHARE}{rel}")).is_file(), "{want} ships");
        }
        // After the plugin is loaded and after the strip's own settings.
        let at = |needle: &str| conf.find(needle).unwrap_or_else(|| panic!("{needle}"));
        assert!(at("plugin = /usr/lib/hyprland/plugins/libhyprbars.so") < at(SYSTEM_HYPR_THEME));
        assert!(at("bar_height = ") < at(SYSTEM_HYPR_THEME));
    }

    #[test]
    fn colour_literals_are_found() {
        for (l, want) in [
            ("bar_color = rgba(2c2c2ee6)", true),
            ("    color = rgb(000000)", true),
            ("col.active_border = 0xff8b6cff", true),
            ("# rgba(00000000) in a comment", false),
            ("gaps_in = 6", false),
            ("bind = $mod, 0, exec, wol-app actual-size", false),
        ] {
            assert_eq!(has_colour(l), want, "{l}");
        }
    }

    /// Every line is a hyprbars/shadow keyword with a valid colour, for every theme, and the live
    /// argv sets exactly the values of the file.
    #[test]
    fn every_theme_colours_the_strip_and_shadows() {
        let cat = ThemeCatalog::builtin();
        for s in cat.list() {
            let t = cat.resolve(&s.id).unwrap();
            let conf = conf(&t);
            let lines: Vec<&str> = conf.lines().filter(|l| !l.starts_with('#')).collect();
            assert_eq!(lines.len(), keywords(&t).len(), "{}", s.id);
            for l in &lines {
                let (k, v) = l.split_once(" = ").unwrap();
                assert!(
                    k.starts_with("plugin:hyprbars:") || k.starts_with("decoration:shadow:"),
                    "{k}"
                );
                let hex = v.strip_prefix("rgba(").and_then(|v| v.strip_suffix(')'));
                assert!(
                    hex.is_some_and(|h| h.len() == 8 && h.chars().all(|c| c.is_ascii_hexdigit())),
                    "{}: {l}",
                    s.id
                );
            }
            let live: Vec<String> = argv(&t)
                .into_iter()
                .map(|a| format!("{} = {}", a[2], a[3]))
                .collect();
            assert_eq!(live, lines, "{}", s.id);
            let bar = token_color(&t, "surface");
            assert!(
                Color::contrast(token_color(&t, "text"), bar) >= 4.5,
                "{}: title on the strip",
                s.id
            );
        }
    }

    #[test]
    fn a_light_theme_gets_a_light_strip() {
        let t = ThemeCatalog::builtin().resolve("catppuccin-latte").unwrap();
        let k = keywords(&t);
        assert_eq!(k[0], ("plugin:hyprbars:bar_color", "rgba(eff1f5e6)".into()));
        assert_eq!(k[1], ("plugin:hyprbars:col.text", "rgba(4c4f69ff)".into()));
    }

    /// The buttons stay the Kit's (`crates/realtime/tests/hypr_conf.rs` checks colours and order).
    #[test]
    fn the_lights_file_holds_only_the_three_buttons() {
        let rel = LIGHTS.strip_prefix("/usr/share/wolos/").unwrap();
        let f = repo(&format!("{SHARE}{rel}"));
        let buttons = f
            .lines()
            .filter(|l| l.trim().starts_with("hyprbars-button"))
            .count();
        assert_eq!(buttons, 3);
        assert!(!f.lines().any(|l| l.trim().starts_with("source")));
    }
}
